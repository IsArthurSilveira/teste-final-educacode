-- Todas as operações dependem de uma sessão emitida pelo Supabase Auth.
-- Não use a anon key para conceder acesso ao banco. Crie os usuários em
-- Authentication > Users e replique o perfil em public.usuarios usando o mesmo e-mail.
CREATE OR REPLACE FUNCTION public.usuario_atual_acesso()
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT acesso
    FROM public.usuarios
    WHERE lower(email) = lower(auth.jwt() ->> 'email')
    LIMIT 1
$$;

DO $$
DECLARE
    tabela TEXT;
BEGIN
    FOREACH tabela IN ARRAY ARRAY[
        'utecs', 'usuarios', 'clubes', 'alunos', 'encontros',
        'roteiros_didaticos', 'clubes_competicao', 'competidores',
        'encontros_competicao', 'projetos_fic_fecom', 'integrantes_projeto',
        'galeria_fotos', 'auditoria'
    ] LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Acesso publico %1$s" ON public.%1$I', tabela);
        EXECUTE format('DROP POLICY IF EXISTS "Acesso autenticado %1$s" ON public.%1$I', tabela);
        EXECUTE format(
            'CREATE POLICY "Acesso autenticado %1$s" ON public.%1$I FOR SELECT TO authenticated USING (auth.uid() IS NOT NULL)',
            tabela
        );
        EXECUTE format(
            'CREATE POLICY "Escrita administrativa %1$s" ON public.%1$I FOR INSERT TO authenticated WITH CHECK (public.usuario_atual_acesso() IN (''superadmin'', ''administrador'', ''editor''))',
            tabela
        );
        EXECUTE format(
            'CREATE POLICY "Atualizacao administrativa %1$s" ON public.%1$I FOR UPDATE TO authenticated USING (public.usuario_atual_acesso() IN (''superadmin'', ''administrador'', ''editor'')) WITH CHECK (public.usuario_atual_acesso() IN (''superadmin'', ''administrador'', ''editor''))',
            tabela
        );
        EXECUTE format(
            'CREATE POLICY "Exclusao administrativa %1$s" ON public.%1$I FOR DELETE TO authenticated USING (public.usuario_atual_acesso() IN (''superadmin'', ''administrador''))',
            tabela
        );
    END LOOP;
END $$;

-- Migração para bancos já existentes: remove a coluna que armazenava senhas.
ALTER TABLE public.usuarios DROP COLUMN IF EXISTS senha;

