-- 2.12 TABELA: galeria_fotos (Acervo Maker de Fotos & Vídeos)
CREATE TABLE IF NOT EXISTS public.galeria_fotos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    titulo TEXT NOT NULL,
    legenda TEXT DEFAULT '',
    descricao TEXT DEFAULT '',
    autor TEXT NOT NULL DEFAULT 'CETEC',
    cargo_autor TEXT DEFAULT '',
    escola TEXT DEFAULT '',
    id_utec BIGINT REFERENCES public.utecs(id) ON DELETE SET NULL,
    clube_nome TEXT DEFAULT '',
    modulo TEXT DEFAULT '',
    data_envio TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    curtidas INTEGER DEFAULT 0,
    consentimento_confirmado BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2.13 TABELA: auditoria (histórico das ações realizadas no sistema)
CREATE TABLE IF NOT EXISTS public.auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
    usuario_nome TEXT NOT NULL DEFAULT '',
    acao TEXT NOT NULL,
    tabela TEXT NOT NULL DEFAULT '',
    id_registro TEXT DEFAULT '',
    detalhes JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

